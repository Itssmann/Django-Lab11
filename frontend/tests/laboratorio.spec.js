import { test, expect } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  const errores = []
  page.on('pageerror', error => errores.push(error.message))
  page.on('console', mensaje => { if (mensaje.type() === 'error') errores.push(mensaje.text()) })
  await page.goto('/')
  page.errores = errores
})
test.afterEach(async ({ page }) => { expect(page.errores).toEqual([]) })

test('cafetería: total, stock, quitar, vaciar, filtros y aviso', async ({ page }) => {
  const mensajes = []
  page.on('console', mensaje => { if (mensaje.type() === 'log') mensajes.push(mensaje.text()) })
  await page.getByRole('button', { name: 'Cafetería', exact: true }).click()
  await page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Capuchino', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true }).click({ clickCount: 2 })
  await page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Café americano', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true }).click()
  await expect(page.locator('.lab-total')).toHaveText('Total: S/ 24.50')
  await expect(page.getByText('Unidades: 3', { exact: true })).toBeVisible()
  await expect(page).toHaveTitle('Carrito (3) — Cafetería')
  expect(mensajes).toContain('Unidades en el carrito: 3')
  await expect(page.locator('.lab-products').getByText('Agotado', { exact: true })).toBeVisible()
  await expect(page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Jugo de naranja', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true })).toBeDisabled()
  await page.locator('.lab-cart li').filter({ hasText: 'Capuchino' }).getByRole('button', { name: 'Quitar', exact: true }).click()
  await expect(page.locator('.lab-total')).toHaveText('Total: S/ 6.50')
  await expect(page.locator('.lab-cart li')).toHaveCount(1)
  await expect(page.getByText('Unidades: 1', { exact: true })).toBeVisible()
  await expect(page).toHaveTitle('Carrito (1) — Cafetería')
  await page.getByRole('button', { name: 'Vaciar carrito' }).click()
  await expect(page.getByText('El carrito está vacío')).toBeVisible()
  await expect(page.getByText('Unidades: 0', { exact: true })).toBeVisible()
  await expect(page).toHaveTitle('Carrito (0) — Cafetería')
  for (let i = 0; i < 5; i++) await page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Torta de chocolate', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true }).click()
  await expect(page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Torta de chocolate', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true })).toBeDisabled()
  await page.locator('.lab-cart li').filter({ hasText: 'Torta de chocolate' }).getByRole('button', { name: 'Quitar', exact: true }).click()
  await expect(page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Torta de chocolate', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true })).toBeEnabled()
  await page.getByRole('searchbox', { name: 'Buscar producto' }).fill('inexistente')
  await expect(page.getByText('No hay productos que coincidan')).toBeVisible()
  await page.getByRole('searchbox', { name: 'Buscar producto' }).fill('capuchino')
  await expect(page.locator('.lab-product:visible')).toHaveCount(1)
  await page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Capuchino', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true }).click()
  await expect(page.getByRole('status').filter({ visible: true })).toContainText('Agregado: Capuchino')
  await page.waitForTimeout(2000)
  await page.locator('.lab-product').filter({ has: page.getByRole('heading', { name: 'Capuchino', exact: true }) }).getByRole('button', { name: 'Agregar', exact: true }).click()
  await page.waitForTimeout(1500)
  await expect(page.getByRole('status').filter({ visible: true })).toContainText('Agregado: Capuchino')
  await expect(page.getByRole('status').filter({ visible: true })).toBeEmpty({ timeout: 4000 })
})

test('prestadores: validaciones, alta, resumen, filtros y callbacks', async ({ page }) => {
  const estadisticas = page.locator('.lab-stat strong')
  await expect(estadisticas).toHaveText(['5', '3', '2'])
  await page.getByRole('button', { name: 'Registrar prestador' }).click()
  await expect(page.getByRole('alert')).toHaveCount(3)
  await page.getByLabel('Nombre completo').fill('Ana Prueba')
  await page.getByLabel('Rubro', { exact: true }).selectOption('Electricidad')
  await page.getByLabel('Teléfono', { exact: true }).fill('812345678')
  await page.getByRole('button', { name: 'Registrar prestador' }).click()
  await expect(page.getByText('Ingresa 9 dígitos;')).toBeVisible()
  await page.getByLabel('Teléfono', { exact: true }).fill('900000001')
  await page.getByRole('button', { name: 'Registrar prestador' }).click()
  await expect(page.getByText('Este teléfono ya está registrado.')).toBeVisible()
  await page.getByLabel('Teléfono', { exact: true }).fill('900000099')
  await page.getByRole('button', { name: 'Registrar prestador' }).click()
  await expect(estadisticas).toHaveText(['6', '4', '2'])
  await expect(page.getByLabel('Nombre completo')).toHaveValue('')
  await page.getByRole('button', { name: 'Desactivar a Ana Prueba', exact: true }).click()
  await expect(estadisticas).toHaveText(['6', '3', '3'])
  await page.getByRole('button', { name: 'Activar a Ana Prueba', exact: true }).click()
  await expect(estadisticas).toHaveText(['6', '4', '2'])
  const buscar = page.getByRole('searchbox', { name: 'Buscar prestadores' })
  await buscar.fill('ana prueba')
  await expect(page.locator('tbody tr:visible')).toHaveCount(1)
  await buscar.fill('gasfiteria')
  await expect(page.locator('tbody tr:visible')).toHaveCount(1)
  await buscar.fill('inexistente')
  await expect(page.getByText('No se encontraron prestadores.')).toBeVisible()
  await expect(estadisticas).toHaveText(['6', '4', '2'])
  await buscar.fill('')
  await page.getByRole('button', { name: 'Eliminar a Ana Prueba' }).click()
  await expect(estadisticas).toHaveText(['5', '3', '2'])
  await expect(page.getByText('Ana Prueba', { exact: true })).toHaveCount(0)
})

test('biblioteca conservada, navegación y diseño móvil', async ({ page }) => {
  await page.getByRole('button', { name: 'Biblioteca', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Biblioteca de barrio — Catálogo' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Lectores', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Prestadores', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('button', { name: 'Registrar prestador' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.getByRole('button', { name: 'Cafetería', exact: true }).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
})
